"""
Confirm-then-save workflow for chat data entry.

Only two fixed, parameterized INSERT statements exist here: one for `orders`
and one for `customers`. No SQL is ever generated by a language model, and
nothing is written until the user explicitly confirms.
"""
import logging
import re
import time
from dataclasses import dataclass, field
from typing import Any

from app.writes.parser import (
    PartialPurchase,
    PurchaseRequest,
    WriteRequestError,
    looks_like_amount,
    parse_amount_only,
)

logger = logging.getLogger(__name__)

CONFIRM_WORDS = frozenset(
    {
        "yes", "y", "yeah", "yep", "yup", "ok", "okay", "sure", "confirm",
        "confirmed", "save", "save it", "do it", "correct", "right",
        "go ahead", "yes please", "please do", "yes save it",
    }
)

CANCEL_WORDS = frozenset(
    {
        "no", "n", "nope", "cancel", "stop", "discard", "dont", "don't",
        "do not", "never mind", "nevermind", "abort", "no thanks",
    }
)

PENDING_TTL_SECONDS = 600


@dataclass
class PendingPurchase:
    request: PurchaseRequest | None
    stage: str  # "need_amount", "choose_customer" or "confirm"
    partial: PartialPurchase | None = None
    customer_id: int | None = None
    customer_name: str = ""
    new_customer: bool = False
    candidates: list[tuple[int, str, str | None]] = field(default_factory=list)
    created_at: float = 0.0


@dataclass
class WriteReply:
    status: str
    message: str
    pending: PendingPurchase | None = None
    details: dict[str, Any] = field(default_factory=dict)


def _normalize_reply(text: str) -> str:
    return " ".join(re.sub(r"[^\w' ]", " ", text.casefold()).split())


def _tokens(text: str) -> set[str]:
    return set(re.findall(r"[^\W\d_]+", text.casefold()))


def _normalized_name(text: str) -> str:
    return " ".join(re.findall(r"[^\W\d_]+", text.casefold()))


def _escape_like(text: str) -> str:
    return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def _money(amount) -> str:
    return f"{amount:,.2f}"


class PurchaseWriter:
    def __init__(self, db=None, clock=time.monotonic):
        self._db = db
        self._clock = clock

    @property
    def db(self):
        if self._db is None:
            from app.db.connection import DatabaseConnection

            self._db = DatabaseConnection()
        return self._db

    # -- lookups -----------------------------------------------------------

    def find_customers(self, name: str) -> list[tuple[int, str, str | None]]:
        pattern = f"%{_escape_like(name)}%"

        with self.db.connect() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    r"SELECT customer_id, name, city FROM customers "
                    r"WHERE name ILIKE %s ESCAPE '\' "
                    r"ORDER BY customer_id LIMIT 50",
                    (pattern,),
                )
                rows = cursor.fetchall()

        wanted = _tokens(name)
        exact = [
            row for row in rows
            if _normalized_name(row[1]) == _normalized_name(name)
        ]
        if exact:
            return list(exact)

        # Whole-word matches only: "Uday" must not match "Sudayan".
        return [row for row in rows if wanted and wanted <= _tokens(row[1])]

    # -- conversation steps ---------------------------------------------------

    def is_expired(self, pending: PendingPurchase) -> bool:
        return self._clock() - pending.created_at > PENDING_TTL_SECONDS

    def prepare(self, request: PurchaseRequest) -> WriteReply:
        matches = self.find_customers(request.customer_name)
        now = self._clock()

        if len(matches) > 1:
            pending = PendingPurchase(
                request=request,
                stage="choose_customer",
                candidates=[tuple(row) for row in matches],
                created_at=now,
            )
            return WriteReply(
                "clarification_required",
                self._choice_message(pending),
                pending,
            )

        if len(matches) == 1:
            customer_id, customer_name, _city = matches[0]
            pending = PendingPurchase(
                request=request,
                stage="confirm",
                customer_id=customer_id,
                customer_name=customer_name,
                created_at=now,
            )
        else:
            pending = PendingPurchase(
                request=request,
                stage="confirm",
                customer_name=request.customer_name,
                new_customer=True,
                created_at=now,
            )

        return WriteReply(
            "confirmation_required",
            self._confirmation_message(pending),
            pending,
        )

    def prepare_partial(self, partial: PartialPurchase) -> WriteReply:
        """Remember a purchase that is only missing its amount."""
        pending = PendingPurchase(
            request=None,
            stage="need_amount",
            partial=partial,
            created_at=self._clock(),
        )
        message = "\n".join(
            [
                "I need the amount for this order:",
                "",
                f"- **Customer:** {partial.customer_name}",
                f"- **Product:** {partial.product}",
                "",
                "How much was it? Reply with an amount such as **80k**, "
                "or **no** to cancel.",
            ]
        )
        return WriteReply("amount_required", message, pending)

    def _pick_candidate(self, pending: PendingPurchase, reply: str):
        if not pending.candidates:
            return None

        if reply.isdigit():
            index = int(reply)
            if 1 <= index <= len(pending.candidates):
                return pending.candidates[index - 1]
            return None

        by_city = [
            candidate for candidate in pending.candidates
            if candidate[2] and _normalize_reply(candidate[2]) == reply
        ]
        return by_city[0] if len(by_city) == 1 else None

    def classify(self, pending: PendingPurchase, text: str) -> str | None:
        reply = _normalize_reply(text)

        if reply in CANCEL_WORDS:
            return "cancel"

        if pending.stage == "need_amount":
            return "amount" if looks_like_amount(text) else None

        if pending.stage == "confirm":
            return "confirm" if reply in CONFIRM_WORDS else None

        return "choice" if self._pick_candidate(pending, reply) else None

    def respond(self, pending: PendingPurchase, text: str) -> WriteReply | None:
        action = self.classify(pending, text)

        if action == "cancel":
            return WriteReply("cancelled", "Okay, nothing was saved.")

        if action == "amount":
            try:
                amount = parse_amount_only(text)
            except WriteRequestError as exc:
                return WriteReply(
                    "invalid_request",
                    f"{exc} How much was it?",
                    pending,
                )

            partial = pending.partial
            return self.prepare(
                PurchaseRequest(
                    customer_name=partial.customer_name,
                    product=partial.product,
                    amount=amount,
                    order_date=partial.order_date,
                )
            )

        if action == "choice":
            customer_id, customer_name, _city = self._pick_candidate(
                pending, _normalize_reply(text)
            )
            chosen = PendingPurchase(
                request=pending.request,
                stage="confirm",
                customer_id=customer_id,
                customer_name=customer_name,
                created_at=self._clock(),
            )
            return WriteReply(
                "confirmation_required",
                self._confirmation_message(chosen),
                chosen,
            )

        if action == "confirm":
            return self.save(pending)

        return None

    # -- the only code that writes -------------------------------------------

    def save(self, pending: PendingPurchase) -> WriteReply:
        request = pending.request

        try:
            with self.db.connect() as connection:
                with connection.cursor() as cursor:
                    customer_id = pending.customer_id

                    if pending.new_customer:
                        cursor.execute(
                            "INSERT INTO customers (name) VALUES (%s) "
                            "RETURNING customer_id",
                            (pending.customer_name,),
                        )
                        customer_id = cursor.fetchone()[0]

                    cursor.execute(
                        "INSERT INTO orders "
                        "(customer_id, product, amount, order_date) "
                        "VALUES (%s, %s, %s, %s) RETURNING order_id",
                        (
                            customer_id,
                            request.product,
                            request.amount,
                            request.order_date,
                        ),
                    )
                    order_id = cursor.fetchone()[0]

        except Exception:
            logger.exception("Saving an order failed.")
            return WriteReply(
                "error",
                "I couldn't save that order and nothing was changed. "
                "Please try again.",
            )

        lines = []
        if pending.new_customer:
            lines.append(
                f"Created customer **{pending.customer_name}** "
                f"(id {customer_id})."
            )
        lines.append(
            f"Saved order **#{order_id}**: {pending.customer_name} bought "
            f"{request.product} for {_money(request.amount)} "
            f"on {request.order_date.isoformat()}."
        )

        return WriteReply(
            "saved",
            "\n\n".join(lines),
            None,
            {
                "order_id": order_id,
                "customer_id": customer_id,
                "customer_created": pending.new_customer,
                "amount": f"{request.amount:.2f}",
                "order_date": request.order_date.isoformat(),
            },
        )

    # -- messages -------------------------------------------------------------

    def _confirmation_message(self, pending: PendingPurchase) -> str:
        request = pending.request

        if pending.new_customer:
            customer = (
                f"{pending.customer_name} "
                "(no customer with this name exists; a new one will be created)"
            )
        else:
            customer = f"{pending.customer_name} (id {pending.customer_id})"

        lines = [
            "I understood this as a new order:",
            "",
            f"- **Customer:** {customer}",
            f"- **Product:** {request.product}",
            f"- **Amount:** {_money(request.amount)}",
            f"- **Date:** {request.order_date.isoformat()}",
        ]

        if request.ignored_text:
            lines.append(f"- **Ignored text:** {request.ignored_text}")

        lines += ["", "Reply **yes** to save it, or **no** to cancel."]
        return "\n".join(lines)

    def _choice_message(self, pending: PendingPurchase) -> str:
        lines = [
            f"More than one customer matches **{pending.request.customer_name}**. "
            "Which one do you mean?",
            "",
        ]

        for number, (customer_id, name, city) in enumerate(
            pending.candidates, start=1
        ):
            place = f" - {city}" if city else ""
            lines.append(f"{number}. {name}{place} (id {customer_id})")

        lines += ["", "Reply with the number, or the city, or **no** to cancel."]
        return "\n".join(lines)