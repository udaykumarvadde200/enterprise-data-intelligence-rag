"""
Add rows to the PostgreSQL database used by the project.

The assistant is read-only by design, so data is NOT added through the chat or
the API. Use this script (or pgAdmin / psql) instead.

Run from the repo root with the venv active:

  python add_data.py                                   show tables and columns
  python add_data.py --table customers --csv c.csv     preview only, nothing saved
  python add_data.py --table customers --csv c.csv --commit    insert the rows

CSV rules:
  - The first row is the header and must use the table's column names.
  - Leave out auto-generated columns (for example an ID that PostgreSQL fills).
  - An empty cell is stored as NULL.
  - All rows go in as one transaction: if any row fails, nothing is saved.

The assistant sees new rows immediately; no restart is needed.
"""
import argparse
import csv
import sys

sys.path.insert(0, ".")

import psycopg  # noqa: E402
from psycopg import sql  # noqa: E402

from app.db.connection import DatabaseConnection  # noqa: E402

SCHEMA_QUERY = """
    SELECT table_name, column_name, data_type, is_nullable,
           column_default, is_identity, identity_generation
    FROM information_schema.columns
    WHERE table_schema = 'public'
    ORDER BY table_name, ordinal_position
"""

PREVIEW_ROWS = 5


class UserError(Exception):
    """A problem with the user's input, reported without a traceback."""


def load_schema(connection):
    tables = {}
    with connection.cursor() as cursor:
        cursor.execute(SCHEMA_QUERY)
        for (
            table,
            column,
            data_type,
            nullable,
            default,
            is_identity,
            generation,
        ) in cursor.fetchall():
            tables.setdefault(table, {})[column] = {
                "type": data_type,
                "required": (
                    nullable == "NO"
                    and default is None
                    and is_identity != "YES"
                ),
                "always_generated": (
                    is_identity == "YES" and generation == "ALWAYS"
                ),
                "auto": default is not None or is_identity == "YES",
            }
    return tables


def print_schema(tables):
    for table, columns in tables.items():
        print(f"\n{table}")
        for name, info in columns.items():
            notes = []
            if info["required"]:
                notes.append("required")
            if info["auto"]:
                notes.append("auto-filled")
            suffix = f"  [{', '.join(notes)}]" if notes else ""
            print(f"  {name}  ({info['type']}){suffix}")
    print()


def read_csv(path):
    try:
        with open(path, newline="", encoding="utf-8-sig") as handle:
            reader = csv.DictReader(handle)
            header = reader.fieldnames
            rows = list(reader)
    except FileNotFoundError:
        raise UserError(f"CSV file not found: {path}")
    except UnicodeDecodeError:
        raise UserError("The CSV must be saved as UTF-8.")

    if not header or any(not name or not name.strip() for name in header):
        raise UserError("The first CSV row must be a header with column names.")

    header = [name.strip() for name in header]
    if len(set(header)) != len(header):
        raise UserError("The CSV header contains a duplicate column name.")
    if not rows:
        raise UserError("The CSV has a header but no data rows.")

    values = []
    for number, row in enumerate(rows, start=2):
        if None in row or any(value is None for value in row.values()):
            raise UserError(
                f"Row {number} has a different number of cells than the header."
            )
        values.append(
            [(value.strip() or None) for value in row.values()]
        )

    return header, values


def check_columns(table, columns, header):
    unknown = [name for name in header if name not in columns]
    if unknown:
        raise UserError(
            f"Unknown column(s) for '{table}': {', '.join(unknown)}. "
            f"Valid columns: {', '.join(columns)}."
        )

    generated = [name for name in header if columns[name]["always_generated"]]
    if generated:
        raise UserError(
            f"Column(s) {', '.join(generated)} are generated by PostgreSQL. "
            "Remove them from the CSV."
        )

    missing = [
        name
        for name, info in columns.items()
        if info["required"] and name not in header
    ]
    if missing:
        raise UserError(
            f"Required column(s) missing from the CSV: {', '.join(missing)}."
        )


def import_csv(connection, tables, table, path, commit):
    if table not in tables:
        raise UserError(
            f"Unknown table '{table}'. Tables: {', '.join(tables)}."
        )

    header, values = read_csv(path)
    check_columns(table, tables[table], header)

    print(f"Table: {table}")
    print(f"Columns: {', '.join(header)}")
    print(f"Rows ready: {len(values)}")
    for row in values[:PREVIEW_ROWS]:
        print("  ", dict(zip(header, row)))
    if len(values) > PREVIEW_ROWS:
        print(f"   ... and {len(values) - PREVIEW_ROWS} more")

    if not commit:
        print("\nPreview only; nothing was saved. Add --commit to insert.")
        return

    query = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
        sql.Identifier(table),
        sql.SQL(", ").join(sql.Identifier(name) for name in header),
        sql.SQL(", ").join(sql.Placeholder() for _ in header),
    )
    with connection.cursor() as cursor:
        cursor.executemany(query, values)

    print(f"\nInserted {len(values)} row(s) into {table}.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--table", help="table to insert into")
    parser.add_argument("--csv", help="path to the CSV file")
    parser.add_argument(
        "--commit",
        action="store_true",
        help="actually insert (without it you only get a preview)",
    )
    args = parser.parse_args()

    try:
        # Leaving the `with` block commits; any error rolls everything back.
        with DatabaseConnection().connect() as connection:
            tables = load_schema(connection)

            if not args.table and not args.csv:
                print_schema(tables)
                print("Add rows with: python add_data.py --table NAME --csv FILE")
                return 0

            if not args.table or not args.csv:
                raise UserError("Use --table and --csv together.")

            import_csv(connection, tables, args.table, args.csv, args.commit)
        return 0

    except UserError as exc:
        print(f"Problem: {exc}")
        return 1
    except psycopg.Error as exc:
        first_line = str(exc).strip().splitlines()[0]
        print(f"Database refused the data (nothing was saved): {first_line}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
